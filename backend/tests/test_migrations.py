"""Migration integrity checks.

The PostgreSQL tests run only when TEST_DATABASE_URL points at a server where the
user may create databases, for example:

    TEST_DATABASE_URL=postgresql+psycopg://postgres@localhost:5432/postgres pytest tests/test_migrations.py

Each test creates and drops its own throwaway database.
"""

import ast
import os
from collections.abc import Generator
from pathlib import Path
from uuid import uuid4

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url

BACKEND_DIR = Path(__file__).resolve().parents[1]
VERSIONS_DIR = BACKEND_DIR / "app" / "db" / "migrations" / "versions"
TEST_DATABASE_URL = os.environ.get("TEST_DATABASE_URL")

requires_postgres = pytest.mark.skipif(
    not TEST_DATABASE_URL, reason="set TEST_DATABASE_URL to run migrations against PostgreSQL"
)


def _alembic_config(database_url: str) -> Config:
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_DIR / "app" / "db" / "migrations"))
    config.attributes["database_url"] = database_url
    return config


@pytest.fixture()
def empty_database() -> Generator[str, None, None]:
    server_url = make_url(TEST_DATABASE_URL)
    name = f"gradebook_migrations_{uuid4().hex[:12]}"
    admin_engine = create_engine(server_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as connection:
        connection.execute(text(f'CREATE DATABASE "{name}"'))
    try:
        yield server_url.set(database=name).render_as_string(hide_password=False)
    finally:
        with admin_engine.connect() as connection:
            connection.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin_engine.dispose()


def _uses_live_models(source: str) -> bool:
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("app.db.models"):
            return True
        if isinstance(node, ast.Import) and any(alias.name.startswith("app.db.models") for alias in node.names):
            return True
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "create_all":
            return True
    return False


def test_migrations_never_import_live_models():
    # A migration that imports the ORM models changes whenever the models change,
    # which is how revision 0001 silently broke fresh installs (issue #1).
    offenders = [path.name for path in sorted(VERSIONS_DIR.glob("*.py")) if _uses_live_models(path.read_text())]
    assert offenders == []


@requires_postgres
def test_fresh_install_matches_models(empty_database: str):
    config = _alembic_config(empty_database)
    command.upgrade(config, "head")
    # Raises AutogenerateDiffsDetected if the migrated schema differs from the models.
    command.check(config)

    engine = create_engine(empty_database)
    try:
        with engine.connect() as connection:
            seeded_templates = connection.execute(text("SELECT count(*) FROM llm_instruction_templates")).scalar_one()
    finally:
        engine.dispose()
    assert seeded_templates >= 4


@requires_postgres
def test_downgrade_to_base_and_upgrade_again(empty_database: str):
    config = _alembic_config(empty_database)
    command.upgrade(config, "head")
    command.downgrade(config, "base")
    command.upgrade(config, "head")
    command.check(config)
